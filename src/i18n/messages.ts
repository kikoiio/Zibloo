export const dictionaries: Record<Locale, Messages> = { 'zh-CN': messages, en };

export function translate(
	locale: Locale,
	key: MessageKey,
	params?: Record<string, string | number>
): string {
	let text: string = dictionaries[locale][key] ?? dictionaries['zh-CN'][key];
	if (params) {
		for (const [name, value] of Object.entries(params)) {
			text = text.replaceAll(`{${name}}`, String(value));
		}
	}
	return text;
}
